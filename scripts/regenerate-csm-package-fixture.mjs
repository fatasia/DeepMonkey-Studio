// Uses the same official compiler request as packageAdapter.csm.test.ts.
import { mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const out = path.join(root, "test-output/interrupted-0930/csm-boundary");
await mkdir(out, { recursive: true });
const require = createRequire(import.meta.url);
const { build } = require("../packages/deep-engine/node_modules/esbuild");
const generated = path.join(out, "fixture-compiler.mjs");
await build({ stdin: { resolveDir: root, sourcefile: "csm-fixture-generator.ts", contents: `
import { adaptDeepSlStandardToShaderPackage } from "./packages/deep-engine/src/shaderAuthoring/packageAdapter.js";
import { ALL_TEXTURES, packageRequest } from "./packages/deep-engine/src/shaderAuthoring/packageAdapter.testFixture.js";
export function compile() {
  const result = adaptDeepSlStandardToShaderPackage({
    ...packageRequest(ALL_TEXTURES.replace("alpha opaque", "alpha mask")), targetAbi: "deep.pbr.mesh.v2",
  });
  if (!result.success) throw new Error(JSON.stringify(result.report));
  return result.package;
}` }, outfile: generated, bundle: true, format: "esm", platform: "node" });
const { compile } = await import(pathToFileURL(generated).href);
const destination = path.join(root, "packages/deep-engine-native/tests/fixtures/deep_shader_package_csm_v2.json");
await writeFile(destination, `${JSON.stringify(compile(), null, 2)}\n`);
console.log(`CSM golden package regenerated by formal compiler: ${destination}`);
