#!/usr/bin/env node
/**
 * J2-B7-codegen：frame ABI 单源生成器（方案 C，规格见
 * docs/specs/frame-abi-unification-spec-20260929.md）。
 *
 * 单一真源 = packages/deep-engine/frame-abi/frame-abi.schema.json；
 * 产物 = TS 常量 / Rust consts / 双端 WGSL struct 文本，均带 schema sha256 指纹戳。
 * 指纹门：产物头戳 == 当前 schema 哈希，手改产物或改 schema 未再生即测试红。
 *
 * 运行：node scripts/generate-frame-abi.mjs（构建期，幂等，重复运行逐字节稳定）。
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(repoRoot, "packages/deep-engine/frame-abi/frame-abi.schema.json");
const schemaBytes = readFileSync(schemaPath);
const schema = JSON.parse(schemaBytes);
const schemaSha256 = createHash("sha256").update(schemaBytes).digest("hex");

const TYPE_ROWS = { mat4: 4, vec4: 1, vec4x2: 2, rows2: 2, scalars16: 4 };
/** Rust 侧跨度（行）。 */
const spanRows = (field) => {
  if (field.type === "block") {
    if (typeof field.rows !== "number") throw new Error(`block 字段 ${field.name} 缺 rows`);
    return field.rows;
  }
  const rows = TYPE_ROWS[field.type];
  if (!rows) throw new Error(`schema 字段 ${field.name} 未知类型 ${field.type}`);
  return rows;
};
/** TS 侧跨度（f32，1 行 = 4 f32）。 */
const spanFloats = (field) => spanRows(field) * 4;

// ---- 校验：TS 侧必须恰好铺满 [0, floats)；Rust 侧行必须恰好铺满 [0, rows) 且零缺口零重叠。
function validateSide(fields, total, unit, spanOf) {
  const sorted = [...fields].sort((a, b) => a[unit] - b[unit]);
  let cursor = 0;
  for (const field of sorted) {
    if (field[unit] !== cursor) {
      throw new Error(`${field.name} 起点 ${field[unit]} ≠ 期望 ${cursor}（缺口或重叠）`);
    }
    cursor += spanOf(field);
  }
  if (cursor !== total) throw new Error(`铺满校验失败：累计 ${cursor} ≠ ${total}`);
  return sorted;
}

const tsFields = [
  ...schema.coreFields.map((field) => ({
    name: field.name, type: field.type, offset: field.ts.offset, core: true, note: field.note,
  })),
  ...schema.tsBand.fields.map((field) => ({ ...field, core: false })),
];
const tsSorted = validateSide(tsFields, schema.hosts.ts.floats, "offset", spanFloats);

const rustFields = [
  ...schema.coreFields.map((field) => ({
    name: field.name, rustName: field.rustName, type: field.type, row: field.rust.row, core: true, note: field.note,
  })),
  ...schema.rustBand.fields.map((field) => ({ ...field, core: false })),
];
const rustSorted = validateSide(rustFields, schema.hosts.rust.rows, "row", spanRows);

if (schema.hosts.rust.floats !== schema.hosts.rust.rows * 4) throw new Error("rust floats/rows 不一致");
if (schema.hosts.ts.bytes !== schema.hosts.ts.floats * 4) throw new Error("ts bytes/floats 不一致");
if (schema.hosts.rust.bytes !== schema.hosts.rust.floats * 4) throw new Error("rust bytes/floats 不一致");

const header = (language) => {
  const comment = language === "rust" ? ["//", "//", "//"] : ["//", "//", "//"];
  return `${comment[0]} GENERATED by scripts/generate-frame-abi.mjs — 手改无效，改 schema 后重新生成。
${comment[1]} source: packages/deep-engine/frame-abi/frame-abi.schema.json
${comment[2]} schema-sha256: ${schemaSha256}
`;
};
const rustHeader = `// GENERATED by scripts/generate-frame-abi.mjs — 手改无效，改 schema 后重新生成。
// source: packages/deep-engine/frame-abi/frame-abi.schema.json
// schema-sha256: ${schemaSha256}
`;

const constName = (field, host) =>
  host === "ts"
    ? `FRAME_ABI_TS_${field.name.replace(/[a-z]/g, "") || field.name}`.toUpperCase().replace(/[^A-Z0-9_]/g, "_")
    : `FRAME_ABI_${field.rustName ?? field.name.replace(/[a-z]/g, "")}`.toUpperCase().replace(/[^A-Z0-9_]/g, "_");

// ---- 产物 1：TS 常量
const tsOut = `${header("ts")}/** J2-B7 单源 frame 布局（方案 C）。迁移完成前与手写常量并存，parity 测试锁一致。 */
export const FRAME_ABI_SCHEMA_SHA256 = "${schemaSha256}";

export const FRAME_ABI_TS_FLOATS = ${schema.hosts.ts.floats};
export const FRAME_ABI_TS_BYTES = ${schema.hosts.ts.bytes};
export const FRAME_ABI_RUST_FLOATS = ${schema.hosts.rust.floats};
export const FRAME_ABI_RUST_BYTES = ${schema.hosts.rust.bytes};
export const FRAME_ABI_RUST_ROWS = ${schema.hosts.rust.rows};

/** 核心段：双端同语义同序，schema 单一定义。 */
export interface FrameAbiCoreField {
  readonly name: string;
  readonly type: string;
  /** TS 侧 f32 偏移。 */
  readonly tsOffset: number;
  /** Rust 侧行号（每行 4 f32）。 */
  readonly rustRow: number;
  readonly note: string;
}
export const FRAME_ABI_CORE: readonly FrameAbiCoreField[] = ${JSON.stringify(
  schema.coreFields.map(({ name, type, ts, rust, note }) => ({
    name, type, tsOffset: ts.offset, rustRow: rust.row, note,
  })), null, 2)};

export const FRAME_ABI_TS_FIELDS: readonly { name: string; type: string; offset: number; core: boolean; note: string }[] = ${JSON.stringify(
  tsSorted.map(({ name, type, offset, core, note }) => ({ name, type, offset, core, note })), null, 2)};

export const FRAME_ABI_RUST_FIELDS: readonly { name: string; rustName: string; type: string; row: number; rows: number; core: boolean; note: string }[] = ${JSON.stringify(
  rustSorted.map(({ name, rustName, type, row, core, note }) => ({
    name, rustName: rustName ?? name, type, row, rows: spanRows({ name, type, rows: rustSorted.find((item) => item.name === name)?.rows }), core, note,
  })), null, 2)};
`;
writeFileSync(join(repoRoot, "packages/deep-engine/src/frameAbi/generated/frameLayout.ts"), tsOut);

// ---- 产物 2：TS 侧 WGSL struct 文本（迁移时由 pbrShader 引用替换手写块）
const tsStructLines = tsSorted.map((field) => {
  const wgslName = field.name;
  const type = field.type === "mat4" ? "mat4x4f" : "vec4f";
  return `  ${wgslName}: ${type},`;
});
const tsWgsl = `// GENERATED frame struct（TS 宿主，96f/384B）— schema-sha256: ${schemaSha256}
struct Frame {
${tsStructLines.join("\n")}
};
`;
writeFileSync(
  join(repoRoot, "packages/deep-engine/src/frameAbi/generated/frameStructsWgsl.ts"),
  `${header("ts")}/** TS 宿主 Frame struct 规范文本；迁移前仅供对拍，不进主着色路径。 */
export const FRAME_STRUCTS_WGSL_SHA256 = "${schemaSha256}";
export const FRAME_STRUCTS_WGSL = ${JSON.stringify(tsWgsl)};
`,
);

// ---- 产物 3：Rust consts（FRAME_ABI_ 前缀避免与手写名冲突；parity 门在 frame_layout_gate.rs）
const rustConsts = rustSorted.map((field) => {
  const name = constName(field, "rust");
  const value = field.row;
  const doc = `/// ${field.note}`;
  return `${doc}\npub const ${name}: usize = ${value};`;
});
const rustOut = `${rustHeader}//! J2-B7 单源 frame 布局（Rust 宿主 ${schema.hosts.rust.abiId}，${schema.hosts.rust.floats}f/${schema.hosts.rust.bytes}B）。
//! 常量带 FRAME_ABI_ 前缀与手写 mesh_abi 常量并存；parity 门见 frame_layout_gate.rs。

pub const FRAME_ABI_SCHEMA_SHA256: &str = "${schemaSha256}";
pub const FRAME_ABI_TS_FLOATS: usize = ${schema.hosts.ts.floats};
pub const FRAME_ABI_TS_BYTES: u64 = ${schema.hosts.ts.bytes};
pub const FRAME_ABI_RUST_FLOATS: usize = ${schema.hosts.rust.floats};
pub const FRAME_ABI_RUST_BYTES: u64 = ${schema.hosts.rust.bytes};
pub const FRAME_ABI_RUST_ROWS: usize = ${schema.hosts.rust.rows};

${rustConsts.join("\n\n")}
`;
writeFileSync(join(repoRoot, "packages/deep-engine-native/src/frame_layout_generated.rs"), rustOut);

// ---- 产物 4：Rust 宿主 WGSL struct 规范文本（行序镜像 mesh_abi v8；迁移前仅供对拍）
const rustWgslLines = [];
for (const field of rustSorted) {
  const type = field.type === "mat4" ? "mat4x4f" : "vec4f";
  if (field.type === "block") {
    rustWgslLines.push(`  // ${field.name}: ${field.rows} 行（${field.note.split("（")[0]}）`);
  } else {
    rustWgslLines.push(`  // row ${field.row}: ${field.name}: ${type}`);
  }
}
const rustWgsl = `// GENERATED frame struct（Rust 宿主，596f/2384B/149 行）— schema-sha256: ${schemaSha256}
// 块字段（灯阵列/阴影矩阵带）以行注释记录区间；标量/矩阵行逐行镜像。
struct NativeFrame {
${rustWgslLines.join("\n")}
};
`;
mkdirSync(join(repoRoot, "packages/deep-engine-native/wgsl"), { recursive: true });
writeFileSync(join(repoRoot, "packages/deep-engine-native/wgsl/frame_structs.wgsl"), rustWgsl);

console.log(`[frame-abi] schema sha256 ${schemaSha256.slice(0, 12)}…`);
console.log(`[frame-abi] ts ${schema.hosts.ts.floats}f 铺满 ✓  rust ${schema.hosts.rust.rows} 行铺满 ✓  产物 4 件已写`);
