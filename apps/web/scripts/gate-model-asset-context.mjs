import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createIsolatedStudioGate } from "./isolatedStudioGate.mjs";
import { collectTextContrast } from "./browserTextContrast.mjs";

const gate = await createIsolatedStudioGate("model-asset-context");
const report = { cases: [] };
try {
  for (const [theme, width] of [["dark", 1440], ["light", 980]]) {
    const entry = { theme, width, passed: false, errors: [], steps: [] }; report.cases.push(entry);
    const context = await gate.browser.newContext({ viewport: { width, height: 1000 } });
    await context.route("**/api/public/branding", async route => { const response = await route.fetch(); await route.fulfill({ response, json: { ...await response.json(), themeMode: theme } }); });
    const page = await context.newPage(); page.setDefaultTimeout(30000);
    page.on("pageerror", error => entry.errors.push(error.message));
    const shot = name => page.screenshot({ path: resolve(gate.output, `${theme}-${width}-${name}.png`) });
    try {
      const project = await gate.json("POST", "/api/projects", { name: `素材闭环-${theme}-${width}` });
      const uploaded = await gate.client.post(`/api/projects/${project.id}/models`, { multipart: { file: { name: "context-source.glb", mimeType: "model/gltf-binary", buffer: await readFile(resolve(import.meta.dirname, "../../../data/external-assets/source-b/models/71df42c5d5964d2ea149c5513bbc061b.glb")) } } });
      assert.equal(uploaded.status(), 202);
      const imported = { model: await uploaded.json() };
      let source;
      for (let i = 0; i < 100; i++) {
        source = (await gate.json("GET", `/api/projects/${project.id}`)).models.find(model => model.id === imported.model.id);
        if (source?.status === "ready") break;
        await page.waitForTimeout(100);
      }
      assert.equal(source?.status, "ready");
      await gate.loginPage(page); await page.goto(`${gate.origin}/manager?project=${project.id}`);
      await page.getByRole("button", { name: "新建场景", exact: true }).click();
      await page.getByLabel("场景名称").fill("模型闭环场景");
      const created = page.waitForResponse(response => response.url().endsWith(`/api/projects/${project.id}/applications`) && response.request().method() === "POST");
      await page.getByRole("button", { name: "创建并进入", exact: true }).click();
      const application = await (await created).json(); const scene = application.scenes[0];
      const appPath = `/api/projects/${project.id}/applications/${application.metadata.id}`;
      const scenePath = `${gate.origin}/studio/${project.id}/applications/${application.metadata.id}/scenes/${scene.id}`;
      await page.goto(scenePath); await page.locator(".viewport canvas").waitFor();
      const auto = page.getByLabel("自动保存"); if (await auto.isChecked()) await auto.uncheck();
      if (!await page.locator(".model-tree-item").count()) await page.getByRole("button", { name: "场景图层与编组", exact: true }).click();
      const tree = id => page.locator(`.app-shell:not(.app-shell-hidden) .model-tree-item[data-model-id="${id}"]`);
      await tree(source.id).locator(".asset-main").click();
      await tree(source.id).getByRole("button", { name: "隐藏", exact: true }).waitFor();
      assert.equal((await gate.json("GET", appPath)).scenes[0].models.length, 0, "Loading with auto-save off is a draft edit");
      await page.route(`**${appPath}/workspace`, route => route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "isolated save failure" }) }));
      await tree(source.id).hover();
      await tree(source.id).getByRole("button", { name: `保存并优化 ${source.name}`, exact: true }).click();
      await page.waitForTimeout(600);
      assert.equal(page.url(), scenePath); assert.equal(await auto.isChecked(), false);
      await shot("save-failed-stays-in-scene");
      await page.unroute(`**${appPath}/workspace`);
      await tree(source.id).getByRole("button", { name: `保存并优化 ${source.name}`, exact: true }).click();
      await page.waitForURL("**/optimizer?**");
      const optimizerUrl = new URL(page.url());
      assert.equal(optimizerUrl.searchParams.get("model"), source.id);
      assert.equal(optimizerUrl.searchParams.get("returnScene"), scene.id);
      const savedOriginal = (await gate.json("GET", appPath)).scenes[0];
      assert.deepEqual(savedOriginal.models.map(model => model.modelId), [source.id]);
      await page.reload();
      await page.waitForFunction(() => document.querySelector(".optimizer-preview-toolbar")?.textContent.includes("模型已载入"));
      assert.equal(await page.getByLabel("从项目素材选择模型").inputValue(), source.id);
      await shot("source-auto-loaded-with-return");
      entry.contrast = await page.locator(".model-asset-workflow").evaluate(collectTextContrast, "strong, small, button, span");
      assert.deepEqual(entry.contrast.filter(item => item.text && item.contrast < 4.5), []);
      await page.getByRole("button", { name: "开始优化", exact: true }).click();
      await page.waitForFunction(() => document.querySelector(".optimizer-preview-toolbar")?.textContent.includes("优化完成"));
      await page.getByRole("button", { name: "保存到项目素材", exact: true }).click();
      await page.getByRole("button", { name: "查看项目素材", exact: true }).waitFor();
      const models = (await gate.json("GET", `/api/projects/${project.id}`)).models;
      const output = models.find(model => model.id !== source.id && model.optimization?.sourceModelId === source.id);
      assert.ok(output); assert.equal(models.length, 2);
      assert.deepEqual((await gate.json("GET", appPath)).scenes[0], savedOriginal, "Optimizer does not write scene content");
      await page.getByRole("button", { name: "查看项目素材", exact: true }).click();
      await page.locator(`.model-library-item[data-model-id="${output.id}"].asset-workflow-selected`).waitFor();
      await page.reload();
      const selected = page.locator(`.model-library-item[data-model-id="${output.id}"].asset-workflow-selected`);
      await selected.waitFor(); await shot("new-asset-located");
      assert.equal(new URL(page.url()).searchParams.get("model"), output.id);
      await selected.getByRole("button", { name: `添加到原场景 ${output.name}`, exact: true }).click();
      await page.waitForURL(url => url.pathname.includes(`/scenes/${scene.id}`) && !url.searchParams.has("addModel"));
      if (!await page.locator(".model-tree-item").count()) await page.getByRole("button", { name: "场景图层与编组", exact: true }).click();
      await tree(output.id).getByRole("button", { name: "隐藏", exact: true }).waitFor();
      assert.match(await tree(output.id).locator(".asset-row").getAttribute("class"), /selected/);
      assert.equal(await auto.isChecked(), false);
      await shot("returned-new-model-selected");
      await page.getByRole("button", { name: /^撤销：/ }).click();
      await page.waitForTimeout(700);
      assert.equal(await tree(output.id).getByRole("button", { name: "展开模型结构", exact: true }).isDisabled(), true);
      await tree(source.id).getByRole("button", { name: "隐藏", exact: true }).waitFor();
      await page.getByRole("button", { name: /^重做：/ }).click();
      await tree(output.id).getByRole("button", { name: "隐藏", exact: true }).waitFor();
      assert.equal(await page.locator(".workspace-recovery-backdrop").count(), 0, "Undo/redo must not offer this live editor's own recovery draft");
      console.log(JSON.stringify({ step: "redo-before-save", url: page.url(), save: await page.getByRole("button", { name: "保存项目", exact: true }).getAttribute("disabled") }));
      await page.getByRole("button", { name: "保存项目", exact: true }).click();
      await page.waitForTimeout(1000);
      const finalScene = (await gate.json("GET", appPath)).scenes[0];
      assert.equal(finalScene.models.length, 2);
      assert.deepEqual(finalScene.models.find(model => model.modelId === source.id), savedOriginal.models[0]);
      await page.goto(`${scenePath}?addModel=${output.id}`);
      await page.waitForURL(url => !url.searchParams.has("addModel"));
      if (!await page.locator(".model-tree-item").count()) await page.getByRole("button", { name: "场景图层与编组", exact: true }).click();
      assert.equal(await tree(output.id).count(), 1);
      await tree(output.id).getByRole("button", { name: "隐藏", exact: true }).click();
      await page.waitForTimeout(800); await page.reload();
      await page.getByRole("dialog", { name: "恢复未保存工作", exact: true }).waitFor();
      await shot("real-reload-still-offers-recovery");
      await page.getByRole("button", { name: "恢复到当前页", exact: true }).click();
      await page.locator(".workspace-recovery-backdrop").waitFor({ state: "detached" });
      if (!await page.locator(".model-tree-item").count()) await page.getByRole("button", { name: "场景图层与编组", exact: true }).click();
      await tree(output.id).getByRole("button", { name: "显示", exact: true }).waitFor();
      assert.deepEqual(entry.errors, []);
      entry.steps.push("save-failure-stays / explicit-save-preserves-draft / URL-source-reload / new-asset-only / focused-assets-reload / return-add-select / one-undo-redo / original-state-preserved / duplicate-idempotent / autosave-remains-off / own-draft-no-false-recovery / real-reload-restores-unsaved-change");
      entry.passed = true;
    } catch (error) { entry.failure = error.stack ?? String(error); entry.url = page.url(); entry.visibleStatus = await page.locator(".viewer-status, .workspace-save-status, .message").allTextContents(); await shot("failed"); }
    finally { await context.close(); console.log(JSON.stringify(entry)); }
    if (!entry.passed) throw new Error(entry.failure);
  }
} finally { await writeFile(resolve(gate.output, "report.json"), JSON.stringify(report, null, 2)); await gate.close(); }
console.log(JSON.stringify({ output: gate.output, report }, null, 2));
assert.equal(report.cases.filter(entry => entry.passed).length, 2);
