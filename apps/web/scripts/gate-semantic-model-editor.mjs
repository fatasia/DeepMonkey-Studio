import assert from "node:assert/strict";
import { createServer } from "node:http";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createIsolatedStudioGate } from "./isolatedStudioGate.mjs";
import { fillSemanticModel, saveSemanticModel } from "./semanticEditorGateActions.mjs";

const source = createServer((_request, response) => { response.setHeader("content-type", "application/json"); response.end(JSON.stringify([{ region: "华东", line: "装配线", amount: 24 }])); });
await new Promise(ready => source.listen(0, "127.0.0.1", ready));
const gate = await createIsolatedStudioGate("semantic-editor");
const report = { createdAt: new Date().toISOString(), cases: [] };
try {
  for (const theme of ["dark", "light"]) for (const width of [1440, 980]) {
    const entry = { theme, width, passed: false, errors: [], expectedHttpErrors: [] };
    report.cases.push(entry);
    const project = await gate.json("POST", "/api/projects", { name: `语义模型验收-${theme}-${width}` });
    const path = `/api/projects/${project.id}`;
    const connection = await gate.json("POST", `${path}/data-connections`, { name: "生产样本", type: "http", enabled: true, config: { url: `http://127.0.0.1:${source.address().port}` } });
    const fields = [{ key: "region", label: "区域", type: "string" }, { key: "line", label: "产线", type: "string" }, { key: "amount", label: "产量", type: "number" }];
    const dataset = await gate.json("POST", `${path}/datasets`, { name: "生产记录", connectionId: connection.id, fields, refreshSeconds: 0 });
    const other = await gate.json("POST", `${path}/datasets`, { name: "不同结构", connectionId: connection.id, fields: [{ key: "unknown", label: "新字段", type: "number" }], refreshSeconds: 0 });
    const pipeline = await gate.json("POST", `${path}/data-pipelines`, { name: "生产输出", nodes: [{ id: "source", type: "source", name: "来源", datasetId: dataset.id, position: { x: 0, y: 0 } }, { id: "out", type: "output", name: "输出", position: { x: 180, y: 0 } }], edges: [{ id: "edge", sourceNodeId: "source", targetNodeId: "out" }] });
    const context = await gate.browser.newContext({ viewport: { width, height: 1000 } });
    await context.route("**/api/public/branding", async route => { const response = await route.fetch(); await route.fulfill({ response, json: { ...await response.json(), themeMode: theme } }); });
    const page = await context.newPage(); page.setDefaultTimeout(12000);
    page.on("pageerror", error => entry.errors.push(error.message));
    page.on("console", message => { if (["warning", "error"].includes(message.type())) { if (/status of (400|409)/.test(message.text())) entry.expectedHttpErrors.push(message.text()); else entry.errors.push(message.text()); } });
    const shot = name => page.screenshot({ path: resolve(gate.output, `${theme}-${width}-${name}.png`), fullPage: true });
    try {
      await gate.loginPage(page);
      await page.getByLabel("当前项目", { exact: true }).selectOption(project.id);
      await page.getByRole("button", { name: "数据中心", exact: true }).click();
      const tab = () => page.locator(".data-hub-tabs").getByRole("button", { name: /语义模型/ });
      await tab().click();
      await page.getByRole("button", { name: "从数据集创建", exact: true }).waitFor();
      await shot("empty");
      await page.getByRole("button", { name: "从数据集创建", exact: true }).click();
      await fillSemanticModel(page, "产线运营口径", dataset.id);
      await shot("complete-draft");
      const created = await saveSemanticModel(page, 201);
      assert.equal(created.metrics.length, 3); assert.equal(created.dimensions[0].hierarchy.length, 2); assert.equal(created.parameters[1].parentKey, "parameter_1");
      assert.equal(created.metrics[1].aggregation, "count"); assert.equal(created.metrics[1].fieldKey ?? "", "");
      assert.equal(created.metrics[2].expression, "amount * 2"); assert.equal(created.metrics[2].fieldKey, undefined);
      const editor = page.locator(".semantic-editor");
      await editor.getByLabel("模型名称", { exact: true }).fill("切页前的未保存输入");
      await page.locator(".data-hub-tabs").getByRole("button", { name: /接入数据/ }).click();
      await tab().click();
      assert.equal(await editor.getByLabel("模型名称", { exact: true }).inputValue(), "切页前的未保存输入");
      page.once("dialog", dialog => dialog.dismiss());
      await editor.getByRole("button", { name: "返回列表", exact: true }).click();
      assert.equal(await editor.getByLabel("模型名称", { exact: true }).inputValue(), "切页前的未保存输入");
      await editor.getByLabel("模型名称", { exact: true }).fill("产线运营口径");
      await editor.getByLabel("模型数据来源", { exact: true }).selectOption(`dataset:${other.id}`);
      await saveSemanticModel(page, 400);
      await editor.locator(".semantic-save-bar [role=alert]").waitFor();
      assert.ok(await editor.locator(".semantic-save-bar li").count() >= 2);
      await shot("invalid-source");
      await editor.getByLabel("模型数据来源", { exact: true }).selectOption(`dataset:${dataset.id}`);
      const updated = await saveSemanticModel(page);
      assert.equal(updated.revision, 2);
      await page.reload(); await tab().click();
      await page.locator(".semantic-model-open").filter({ hasText: "产线运营口径" }).click();
      assert.equal(await editor.getByLabel("模型名称", { exact: true }).inputValue(), "产线运营口径");
      const saved = (await gate.json("GET", `${path}/semantic-models`))[0];
      assert.equal(saved.parameters[0].optionsSource.options[0].value, "华东");
      await editor.getByRole("button", { name: "返回列表", exact: true }).click();
      await page.getByRole("button", { name: "重命名 产线运营口径", exact: true }).click();
      await page.getByLabel("新模型名称", { exact: true }).fill("统一生产口径");
      await page.getByRole("button", { name: "确认重命名", exact: true }).click();
      await page.getByRole("button", { name: "重命名 统一生产口径", exact: true }).waitFor();
      await shot("list");
      await page.getByRole("button", { name: "新建模型", exact: true }).click();
      await editor.getByLabel("模型名称", { exact: true }).fill("统一生产口径");
      await editor.getByLabel("模型数据来源", { exact: true }).selectOption(`pipeline:${pipeline.id}`);
      await editor.getByRole("button", { name: "从预览导入字段", exact: true }).click();
      await page.waitForFunction(() => document.querySelectorAll(".semantic-pipeline-field").length === 3);
      await saveSemanticModel(page, 409);
      await editor.getByLabel("模型名称", { exact: true }).fill("管道业务口径");
      await saveSemanticModel(page, 201);
      await shot("pipeline-fields");
      await editor.getByRole("button", { name: "返回列表", exact: true }).click();
      page.once("dialog", dialog => dialog.dismiss());
      await page.getByRole("button", { name: "删除 管道业务口径", exact: true }).click();
      assert.equal((await gate.json("GET", `${path}/semantic-models`)).length, 2);
      page.once("dialog", dialog => dialog.accept());
      const removed = page.waitForResponse(response => response.url().includes("/semantic-models/") && response.request().method() === "DELETE");
      await page.getByRole("button", { name: "删除 管道业务口径", exact: true }).click();
      assert.equal((await removed).status(), 204);
      assert.equal((await gate.json("GET", `${path}/semantic-models`)).length, 1);
      await page.getByLabel("搜索语义模型", { exact: true }).fill("不存在");
      await page.getByText("没有匹配的模型", { exact: true }).waitFor();
      assert.deepEqual(entry.errors, []);
      entry.passed = true;
    } catch (error) { entry.failure = error.stack ?? String(error); await shot("failed"); }
    finally { await context.close(); }
  }
} finally { await writeFile(resolve(gate.output, "report.json"), JSON.stringify(report, null, 2)); await gate.close(); await new Promise(done => source.close(done)); }
console.log(JSON.stringify({ ...report, output: gate.output }, null, 2));
assert.ok(report.cases.length === 4 && report.cases.every(entry => entry.passed), "Semantic editor gate failed");
