import assert from "node:assert/strict";
import { blankPoint, runDashboardGate, waitCount } from "./dashboardInteractionGate.mjs";

await runDashboardGate("selection", async (page, output) => {
  const { x, y, box } = await blankPoint(page);
  await page.mouse.move(x, y);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width - 30, box.y + 30, { steps: 20 });
  await page.mouse.up();
  await waitCount(page, ".dashboard-node.selected", 9);
  await page.screenshot({ path: `${output}-marquee.png` });
  await page.mouse.click(x, y);
  await waitCount(page, ".dashboard-node.selected", 0);
  const nodes = page.locator(".dashboard-node");
  // locator.click 才支持 modifiers；mouse.click 不会真正按下 Shift。
  await nodes.nth(1).click({ modifiers: ["Shift"] });
  await waitCount(page, ".dashboard-node.selected", 1);
  await nodes.nth(2).click({ modifiers: ["Shift"] });
  await waitCount(page, ".dashboard-node.selected", 2);
  await nodes.nth(1).click({ modifiers: ["Control"] });
  await waitCount(page, ".dashboard-node.selected", 1);
  await page.screenshot({ path: `${output}-selection.png` });
  assert.equal(await page.locator(".dashboard-page-row").count(), 0);
  await page.getByRole("button", { name: "复制当前页面", exact: true }).click();
  await waitCount(page, '[role="tab"]', 2);
  await waitCount(page, ".dashboard-node", 9);
  assert.match(await page.getByRole("tab", { selected: true }).innerText(), /副本/);
  await page.getByRole("button", { name: "删除当前页面", exact: true }).click();
  await waitCount(page, '[role="tab"]', 1);
  await page.getByRole("button", { name: "新增空白页面", exact: true }).click();
  await waitCount(page, ".dashboard-node", 0);
  await page.getByRole("tab", { selected: true }).press("ArrowLeft");
  await waitCount(page, ".dashboard-node", 9);
  await page.getByRole("tab", { selected: true }).press("End");
  await waitCount(page, ".dashboard-node", 0);
  await page.getByRole("button", { name: "删除当前页面", exact: true }).click();
  await waitCount(page, '[role="tab"]', 1);
  assert.equal(await page.getByRole("button", { name: "删除当前页面", exact: true }).isDisabled(), true);
  await page.screenshot({ path: `${output}-page-actions.png` });
  return { marquee: 9, shiftAdd: 2, ctrlToggle: 1, pageActions: "copy / add / keyboard switch / delete / last-page guard" };
});
