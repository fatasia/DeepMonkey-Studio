import playwright from "../../cloud-render-worker/node_modules/playwright-core/index.js";
const { chromium } = playwright;
const browser = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const logs = [];
page.on("console", (m) => { if (m.text().includes("[u112]")) logs.push(m.text()); });
await page.goto("http://127.0.0.1:5173", { waitUntil: "domcontentloaded", timeout: 60000 });
await page.getByLabel("用户名").fill("admin");
await page.getByLabel("密码").fill("admin");
await page.getByRole("button", { name: "登录" }).click();
await page.waitForTimeout(3000);
await page.locator(".scene-card-actions button[aria-label='编辑场景']").first().click();
await page.waitForTimeout(9000);
const scrollBox = await page.locator(".dashboard-canvas-scroll").boundingBox();
await page.mouse.move(scrollBox.x + 45, scrollBox.y + scrollBox.height - 45);
await page.mouse.down();
await page.mouse.move(scrollBox.x + scrollBox.width - 45, scrollBox.y + 45, { steps: 12 });
await page.mouse.up();
await page.waitForTimeout(400);
const selected = await page.locator(".dashboard-node.selected").count();
console.log(JSON.stringify({ logs: logs.slice(0, 10), selected }, null, 2));
await browser.close();
