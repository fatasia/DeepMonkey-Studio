import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { createIsolatedStudioGate } from "./isolatedStudioGate.mjs";
import { collectTextContrast } from "./browserTextContrast.mjs";
import { attachWorkerDebugger, waitForValue } from "./authorDebugProtocol.mjs";
import { createDebugFixture } from "./authorDebugFixture.mjs";

const gate = await createIsolatedStudioGate("author-script-debug");
const report = { createdAt: new Date().toISOString(), browserVersion: gate.browser.version(), bundleSha256: createHash("sha256").update(await readFile(new URL("../dist/index.html", import.meta.url))).digest("hex"), cases: [] };
try {
  for (const theme of ["dark", "light"]) for (const width of [1440, 980]) {
    const entry = { theme, width, passed: false, errors: [], writes: 0, workers: 0, closedWorkers: 0, steps: [] };
    report.cases.push(entry);
    const fixture = await createDebugFixture(gate, theme, width, theme === "light");
    const { project, application } = fixture;
    const appPath = `/api/projects/${project.id}/applications/${application.metadata.id}`;
    const before = await gate.json("GET", appPath);
    const context = await gate.browser.newContext({ viewport: { width, height: 900 }, permissions: ["clipboard-read", "clipboard-write"] });
    await context.route("**/api/public/branding", async route => { const response = await route.fetch(); await route.fulfill({ response, json: { ...await response.json(), themeMode: theme, primaryColor: "#8456d9" } }); });
    const page = await context.newPage(); page.setDefaultTimeout(20000);
    page.on("pageerror", error => entry.errors.push(error.message));
    page.on("console", message => { if (["error", "warning"].includes(message.type())) entry.errors.push(message.text()); });
    page.on("request", request => { if (request.url().endsWith(appPath) && request.method() === "PUT") entry.writes++; });
    page.on("worker", worker => { if (worker.url().includes("sceneBehavior.worker")) { entry.workers++; worker.on("close", () => entry.closedWorkers++); } });
    let debuggerClient;
    const shot = name => page.screenshot({ path: resolve(gate.output, `${theme}-${width}-${name}.png`) });
    const debug = async () => {
      await page.getByLabel("更多工具", { exact: true }).click();
      await page.getByRole("button", { name: "DevTools 调试当前脚本", exact: true }).click();
      await page.getByRole("button", { name: "开始执行", exact: true }).waitFor();
    };
    try {
      await gate.loginPage(page);
      await page.goto(`${gate.origin}/studio/${project.id}/applications/${application.metadata.id}/pages/page`);
      await page.getByRole("button", { name: "脚本", exact: true }).click();
      await page.locator(".monaco-editor .view-lines").waitFor();
      assert.equal((await page.locator(".behavior-split-resizer").boundingBox()).width, 10, "Splitter styles must load before any preview");
      assert.equal((await page.locator(".behavior-script-list-resizer").boundingBox()).width, 5);
      // With no debugger attached the host still reports only source readiness;
      // starting executes normally and never fabricates a breakpoint state.
      await debug();
      await page.getByText("源码就绪，等待开始执行", { exact: true }).waitFor();
      await page.getByRole("button", { name: "开始执行", exact: true }).click();
      await page.locator(".author-behavior-preview").getByText("RESULT 42", { exact: true }).waitFor();
      await page.getByRole("button", { name: "停止运行", exact: true }).click();
      await page.locator(".author-behavior-preview").waitFor({ state: "detached" });
      entry.steps.push("without-debugger-explicit-start-no-fake-pause");
      debuggerClient = await attachWorkerDebugger(context, page);
      await debug();
      const { target, script } = await debuggerClient.source(fixture.sourceUrl);
      entry.source = { url: script.url, lineOffset: fixture.lineOffset, workerName: target.info.title };
      const runtimeSource = (await debuggerClient.send(target, "Debugger.getScriptSource", { scriptId: script.scriptId })).scriptSource;
      const line = text => runtimeSource.split("\n").findIndex(value => value.includes(text));
      assert.equal(line("const value = addTwo"), fixture.source.split("\n").findIndex(value => value.includes("const value = addTwo")) + fixture.lineOffset);
      assert.equal(await page.getByRole("textbox", { name: "调试源码文件", exact: true }).inputValue(), fixture.sourceUrl);
      assert.equal(await page.getByRole("button", { name: "推进一帧（1/60 秒，非源码单步）", exact: true }).isDisabled(), true);
      await page.getByRole("button", { name: "复制源码文件名", exact: true }).click();
      await page.getByText("已复制", { exact: true }).waitFor();
      assert.equal(await page.evaluate(() => navigator.clipboard.readText()), fixture.sourceUrl);
      const instructions = page.getByText("调试运行说明", { exact: true });
      await instructions.focus(); await page.keyboard.press("Enter");
      assert.equal(await instructions.locator("..").getAttribute("open"), "");
      await page.keyboard.press("Escape");
      assert.equal(await instructions.locator("..").getAttribute("open"), null);
      await shot("ready");
      const breakpoint = await debuggerClient.send(target, "Debugger.setBreakpointByUrl", { url: fixture.sourceUrl, lineNumber: line("const value = addTwo") });
      assert.ok(breakpoint.locations.length);
      await page.getByRole("button", { name: "开始执行", exact: true }).click();
      let paused = await debuggerClient.pause(target);
      const inspect = async expression => (await debuggerClient.send(target, "Debugger.evaluateOnCallFrame", { callFrameId: paused.callFrames[0].callFrameId, expression, returnByValue: true, throwOnSideEffect: true })).result.value;
      assert.equal(paused.callFrames[0].functionName, "onStart");
      const initial = await inspect("initial");
      assert.equal(initial, 40);
      assert.equal(await inspect("ctx.state.frame"), 0);
      await page.waitForTimeout(2600);
      assert.equal(target.detached, false, "A real breakpoint must survive the normal 25 ms lifecycle and 2 s initialization thresholds");
      assert.equal(await inspect("ctx.state.frame"), 0);
      await page.getByText("会话已启动；断点状态见 DevTools", { exact: true }).waitFor();
      const preview = page.getByRole("region", { name: "脚本隔离预览", exact: true });
      await preview.getByText("AUTHOR ORIGINAL", { exact: true }).waitFor();
      entry.initialCallStack = paused.callFrames.map(frame => frame.functionName);
      await shot("real-breakpoint");
      await debuggerClient.send(target, "Debugger.stepInto");
      paused = await debuggerClient.pause(target, 1);
      assert.equal(paused.callFrames[0].functionName, "addTwo");
      assert.equal(paused.callFrames[1].functionName, "onStart");
      const input = await inspect("input");
      assert.equal(input, 40);
      await debuggerClient.send(target, "Debugger.stepOver");
      paused = await debuggerClient.pause(target, 2);
      const result = await inspect("result");
      assert.equal(result, 42);
      entry.nestedCallStack = paused.callFrames.map(frame => frame.functionName);
      entry.variables = { initial, input, result };
      await debuggerClient.send(target, "Debugger.removeBreakpoint", { breakpointId: breakpoint.breakpointId });
      await debuggerClient.send(target, "Debugger.resume");
      await preview.getByText("RESULT 42", { exact: true }).waitFor();
      const frameBreakpoint = await debuggerClient.send(target, "Debugger.setBreakpointByUrl", { url: fixture.sourceUrl, lineNumber: line("ctx.state.frame += 1") });
      paused = await debuggerClient.pause(target, 3);
      const frameBefore = await inspect("ctx.state.frame");
      const timeBefore = await inspect("ctx.elapsedMs");
      await page.waitForTimeout(1200);
      assert.equal(await inspect("ctx.state.frame"), frameBefore);
      await debuggerClient.send(target, "Debugger.resume");
      paused = await debuggerClient.pause(target, 4);
      const frameAfter = await inspect("ctx.state.frame"), timeAfter = await inspect("ctx.elapsedMs");
      entry.resume = { frameBefore, frameAfter, timeBefore, timeAfter, elapsedDelta: timeAfter - timeBefore, breakpointWaitMs: 1200 };
      assert.equal(frameAfter, frameBefore + 1);
      assert.ok(timeAfter - timeBefore < 250, "Debugger waiting time must not accumulate into simulation time");
      await page.getByRole("button", { name: "停止运行", exact: true }).click();
      await preview.waitFor({ state: "detached" });
      await waitForValue(() => target.detached, "paused Worker termination");
      await page.waitForTimeout(150);
      await page.getByText("AUTHOR ORIGINAL", { exact: true }).waitFor();
      assert.equal(entry.writes, 0);
      assert.deepEqual(await gate.json("GET", appPath), before);
      entry.steps.push("real-source-breakpoint", "real-step-into-and-over", "real-call-stack-and-local-values", "wait-survives-watchdogs", "resume-without-time-backlog", "stop-while-paused-no-author-write");
      await debug();
      const rerun = await debuggerClient.source(fixture.sourceUrl, target);
      assert.notEqual(rerun.target.sessionId, target.sessionId);
      await debuggerClient.send(rerun.target, "Debugger.setBreakpointByUrl", { url: fixture.sourceUrl, lineNumber: line("const value = addTwo") });
      await page.getByRole("button", { name: "开始执行", exact: true }).click();
      await debuggerClient.pause(rerun.target);
      await page.locator(".behavior-script-list > button").filter({ hasText: "普通脚本" }).click();
      await preview.waitFor({ state: "detached" });
      await waitForValue(() => rerun.target.detached, "Worker termination after script switch");
      entry.steps.push("stable-source-identity-on-rerun", "script-switch-terminates-paused-worker");
      await page.locator(".behavior-script-list > button").filter({ hasText: "断点验证" }).click();
      await debug();
      entry.contrast = await page.locator("body").evaluate(collectTextContrast, ".author-debug-heading strong, .author-debug-heading > span, .author-debug-notice p, .author-debug-notice summary, .author-debug-source input");
      assert.deepEqual(entry.contrast.filter(item => item.text && item.contrast < 4.5), []);
      const notice = await page.locator(".author-debug-notice").boundingBox();
      const editor = await page.locator(".behavior-editor").boundingBox();
      assert.ok(notice.x >= editor.x && notice.x + notice.width <= editor.x + editor.width + 1);
      assert.ok((await page.locator(".monaco-editor").boundingBox()).height > 100);
      assert.equal((await page.locator(".behavior-split-resizer").boundingBox()).width, 10, "Generic button target size must not widen the transparent splitter");
      assert.equal((await page.locator(".behavior-script-list-resizer").boundingBox()).width, 5, "The file-list splitter must not cover code controls");
      const close = page.getByRole("button", { name: "隐藏脚本编辑器", exact: true });
      assert.equal(await close.evaluate(button => { const rect = button.getBoundingClientRect(); return document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2)?.closest("button") === button; }), true);
      await shot("final-ready");
      const exiting = await debuggerClient.source(fixture.sourceUrl, rerun.target);
      await debuggerClient.send(exiting.target, "Debugger.setBreakpointByUrl", { url: fixture.sourceUrl, lineNumber: line("const value = addTwo") });
      await page.getByRole("button", { name: "开始执行", exact: true }).click();
      await debuggerClient.pause(exiting.target);
      await close.click();
      await preview.waitFor({ state: "detached" });
      await waitForValue(() => exiting.target.detached, "closing the editor terminates a truly paused Worker");
      await waitForValue(() => entry.closedWorkers === entry.workers, "all debug Workers terminated");
      assert.deepEqual(debuggerClient.errors, []); assert.deepEqual(entry.errors, []);
      assert.equal(entry.writes, 0); assert.deepEqual(await gate.json("GET", appPath), before);
      entry.steps.push("close-editor-disposes-paused-worker", "clipboard-and-layout-and-contrast", "all-workers-closed");
      entry.passed = true;
    } catch (error) {
      entry.failure = error.stack ?? String(error);
      entry.visiblePanel = await page.locator(".behavior-panel").innerText().catch(() => "");
      if (debuggerClient) entry.protocol = [...debuggerClient.targets.values()].map(target => ({ info: target.info, detached: target.detached, sourceUrls: target.scripts.map(script => script.url), pauses: target.pauses.map(pause => ({ reason: pause.reason, callFrames: pause.callFrames.map(frame => ({ name: frame.functionName, location: frame.location })) })) }));
      await shot("failed");
    } finally { await debuggerClient?.close(); await context.close(); console.log(JSON.stringify(entry)); }
  }
} finally { await writeFile(resolve(gate.output, "report.json"), JSON.stringify(report, null, 2)); await gate.close(); }
console.log(JSON.stringify({ output: gate.output, report }, null, 2));
assert.equal(report.cases.filter(entry => entry.passed).length, 4);
