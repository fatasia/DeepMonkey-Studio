import assert from "node:assert/strict";
import { runDashboardGate, settleFrames } from "./dashboardInteractionGate.mjs";

const fixtures = new WeakMap();
const fields = [{ key: "region", label: "区域", type: "string" }, { key: "amount", label: "产量", type: "number", unit: "件" }, { key: "category", label: "工序", type: "string" }];
const datasets = [{ id: "field-qa", projectId: "visual-qa", name: "生产指标", fields, computedFields: [{ id: "computed", key: "double", label: "双倍产量", type: "number", formula: "amount * 2" }], refreshSeconds: 0, connectionId: "fixture" }];
const pipelines = [{ id: "pipeline-qa", projectId: "visual-qa", name: "汇总管道", nodes: [{ id: "source", type: "source", datasetId: "field-qa" }], edges: [] }];
const rows = [{ region: "一区", amount: 18, category: "装配", double: 36 }, { region: "二区", amount: 22, category: "测试", double: 44 }];

await runDashboardGate("dashboard-field-binding", async (page, output) => {
  const fixture = fixtures.get(page);
  await page.locator(".dashboard-node").nth(5).click();
  await page.locator(".dashboard-inspector-tabs").getByRole("button", { name: "数据", exact: true }).click();
  await page.getByRole("button", { name: "选字段", exact: true }).click();
  const panel = page.locator(".dashboard-field-panel");
  await panel.getByRole("button", { name: /生产指标/ }).click();
  await panel.locator(".dashboard-field-row").filter({ hasText: "双倍产量" }).waitFor();
  const slot = (role) => page.locator(`[data-field-role="${role}"]`);
  const trigger = (role) => slot(role).locator(".dashboard-slot-trigger");
  const field = (label) => panel.locator(".dashboard-field-row").filter({ has: page.locator("strong", { hasText: new RegExp(`^${label}$`) }) });
  assert.equal(await page.locator(".dashboard-field-slot").count(), 3);
  await field("产量").dragTo(slot("measure"));
  await page.waitForFunction(() => document.querySelector('[data-field-role="measure"] .dashboard-slot-trigger')?.textContent.includes("产量"));
  assert.match(await page.getByLabel("数据产品", { exact: true }).inputValue(), /dataset:field-qa/);
  assert.match(await trigger("dimension").innerText(), /拖入维度/);
  await page.getByRole("button", { name: "撤销", exact: true }).click();
  assert.match(await trigger("measure").innerText(), /拖入指标/);
  assert.equal(await page.getByRole("button", { name: "撤销", exact: true }).isDisabled(), true, "一次跨产品拖入只能有一条命令");
  await page.getByRole("button", { name: "重做", exact: true }).click();
  await field("区域").dragTo(slot("dimension"));
  await field("工序").dragTo(slot("series"));
  assert.match(await trigger("dimension").innerText(), /区域/);
  assert.match(await trigger("series").innerText(), /工序/);
  await field("区域").dragTo(slot("measure"));
  assert.match(await trigger("measure").innerText(), /产量/, "文本不得覆盖数值指标");
  await page.screenshot({ path: `${output}-bound.png` });
  await slot("measure").getByRole("button", { name: "解绑指标", exact: true }).click();
  assert.match(await trigger("measure").innerText(), /拖入指标/);
  await page.getByRole("button", { name: "撤销", exact: true }).click();
  assert.match(await trigger("measure").innerText(), /产量/);
  await trigger("measure").focus();
  await page.keyboard.press("Enter");
  await page.getByRole("listbox").waitFor();
  await page.keyboard.press("End");
  await page.keyboard.press("Enter");
  assert.match(await trigger("measure").innerText(), /双倍产量/);
  await page.keyboard.press("ArrowUp");
  assert.equal(await trigger("dimension").evaluate((element) => element === document.activeElement), true);
  await page.keyboard.press("Enter");
  await page.keyboard.press("Escape");
  assert.equal(await page.getByRole("listbox").count(), 0);
  await panel.getByRole("button", { name: /汇总管道/ }).click();
  await panel.getByRole("alert").filter({ hasText: "QA 来源暂不可达" }).waitFor();
  fixture.pipelineFails = false;
  await panel.getByRole("button", { name: "重试字段预览", exact: true }).click();
  await panel.getByRole("list", { name: "汇总管道", exact: true }).locator(".dashboard-field-row").first().waitFor();
  await panel.getByLabel("搜索数据字段").fill(" double ");
  assert.equal(await panel.locator(".dashboard-field-row").count(), 1);
  await panel.getByLabel("搜索数据字段").fill("无匹配结果");
  await panel.getByText("没有匹配的字段", { exact: true }).waitFor();
  await panel.getByLabel("搜索数据字段").fill("");
  await settleFrames(page);
  const geometry = await page.evaluate(() => {
    const panel = document.querySelector(".dashboard-field-panel"), inspector = document.querySelector(".dashboard-inspector-panel");
    const a = panel.getBoundingClientRect(), b = inspector.getBoundingClientRect();
    return { panelWidth: a.width, panelRight: a.right, inspectorLeft: b.left, overflow: panel.scrollWidth > panel.clientWidth + 1, bodyOverflow: document.documentElement.scrollWidth > innerWidth };
  });
  assert.ok(geometry.panelWidth >= 240 && geometry.panelRight <= geometry.inspectorLeft + 1, JSON.stringify(geometry));
  assert.equal(geometry.overflow || geometry.bodyOverflow, false);
  await page.screenshot({ path: `${output}-keyboard-pipeline.png` });
  fixture.empty = true;
  await panel.getByRole("button", { name: "刷新字段目录", exact: true }).click();
  await panel.getByText("数据中心还没有数据产品", { exact: true }).waitFor();
  await page.screenshot({ path: `${output}-empty.png` });
  fixture.empty = false;
  await page.reload({ waitUntil: "domcontentloaded" });
  await panel.waitFor(); // 仅展开偏好持久化；DEV 文档本身不假装已保存。
  assert.ok(await panel.isVisible());
  return { geometry, atomicUndo: true, keyboardBinding: true, typeRejection: true, pipelineFailureRetry: true, computedFieldSearch: true, empty: true, openPreferenceRestored: true };
}, async (page) => {
  const fixture = { empty: false, pipelineFails: true };
  fixtures.set(page, fixture);
  await page.route("**/api/projects/visual-qa/**", async (route) => {
    const path = new URL(route.request().url()).pathname;
    assert.equal(route.request().method(), "GET");
    let body;
    if (path.endsWith("/datasets")) body = fixture.empty ? [] : datasets;
    else if (path.endsWith("/data-pipelines")) body = fixture.empty ? [] : pipelines;
    else if (path.endsWith("/datasets/field-qa/preview")) body = { dataset: datasets[0], fields: [...fields, ...datasets[0].computedFields], rows };
    else if (path.endsWith("/data-pipelines/pipeline-qa/preview")) body = fixture.pipelineFails ? { status: "error", error: "QA 来源暂不可达", fields: [], rows: [] } : { status: "success", pipeline: pipelines[0], fields, rows };
    else throw new Error(`Unexpected fixture request: ${path}`);
    await route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify(body) });
  });
});
